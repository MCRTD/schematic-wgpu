//! Wavefront OBJ output: `<stem>.obj`, `<stem>.mtl` and `<stem>.png`.
//!
//! Tints are written as per-vertex colors (`v x y z r g b`), an extension
//! that Blender, MeshLab and most other tools read.

use std::fmt::Write;

use mesher::{Mesh, Transparency};

use crate::{File, crisp_atlas_png};

fn material_name(t: Transparency) -> &'static str {
    match t {
        Transparency::Opaque => "opaque",
        Transparency::Cutout => "cutout",
        Transparency::Translucent => "translucent",
    }
}

pub fn obj(mesh: &Mesh, name: &str, stem: &str) -> Vec<File> {
    let mut obj = String::new();
    let mut mtl = String::new();
    let _ = writeln!(obj, "# generated by schematic-wgpu\nmtllib {stem}.mtl\no {name}");

    // OBJ indices are global and 1-based.
    let mut base = 1;
    for (transparency, layer) in mesh.layers() {
        if layer.is_empty() {
            continue;
        }
        let material = material_name(transparency);
        let _ = writeln!(mtl, "newmtl {material}\nKa 1 1 1\nKd 1 1 1\nKs 0 0 0\nillum 1\nmap_Kd {stem}.png");
        if transparency != Transparency::Opaque {
            let _ = writeln!(mtl, "map_d {stem}.png");
        }
        mtl.push('\n');

        for v in &layer.vertices {
            let [x, y, z] = v.position;
            let _ = write!(obj, "v {x} {y} {z}");
            if v.color != [255; 4] {
                let [r, g, b, _] = v.color.map(|c| c as f32 / 255.0);
                let _ = write!(obj, " {r:.4} {g:.4} {b:.4}");
            }
            obj.push('\n');
        }
        for v in &layer.vertices {
            // OBJ puts v=0 at the bottom of the image, glTF and our atlas at the top.
            let _ = writeln!(obj, "vt {} {}", v.uv[0], 1.0 - v.uv[1]);
        }
        for v in &layer.vertices {
            let [x, y, z] = v.normal;
            let _ = writeln!(obj, "vn {x} {y} {z}");
        }
        let _ = writeln!(obj, "g {material}\nusemtl {material}");
        for tri in layer.indices.chunks_exact(3) {
            let [a, b, c] = [tri[0], tri[1], tri[2]].map(|i| i as usize + base);
            let _ = writeln!(obj, "f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}");
        }
        base += layer.vertices.len();
    }

    vec![
        File { name: format!("{stem}.obj"), data: obj.into_bytes() },
        File { name: format!("{stem}.mtl"), data: mtl.into_bytes() },
        File { name: format!("{stem}.png"), data: crisp_atlas_png(mesh) },
    ]
}
